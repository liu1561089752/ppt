/**
 * history-view.tsx — Task 4-b 生成历史视图
 *
 * 顶部"立即生成"快捷按钮
 * 任务列表:每张卡片含 topic / 状态 badge / 创建时间 / 耗时 / 元信息 / 失败原因 / 下载按钮
 * 自动刷新:有进行中任务时每 3 秒拉一次
 * 空状态 + 分页
 *
 * 响应式:mobile-first,max-w-5xl 单栏
 */
'use client'

import * as React from 'react'
import { useQuery, useQueryClient } from '@tanstack/react-query'
import { toast } from 'sonner'
import { motion } from 'framer-motion'
import {
  Plus,
  Clock,
  XCircle,
  Loader2,
  Square,
  Download,
  FileText,
  Eye,
  Sparkles,
  History as HistoryIcon,
  Tag,
  Languages,
  Layers,
  MessageCircleQuestion,
} from 'lucide-react'

import { cn } from '@/lib/utils'
import { apiGet, apiPost } from '@/lib/api-client'
import { useAppStore } from '@/store/app-store'
import {
  statusMeta,
  isTaskActive,
  PRESET_LABELS,
  LANGUAGE_LABELS,
  type TaskStatus,
} from '@/lib/meta'
import { formatDate, formatDuration, formatRelative } from '@/lib/format'
import { PaginationFooter } from '@/components/pagination-footer'
import {
  NativeDeckPreviewDialog,
} from '@/components/ppt-preview'

import {
  Card,
  CardContent,
  CardDescription,
  CardTitle,
} from '@/components/ui/card'
import { Button } from '@/components/ui/button'
import { Badge } from '@/components/ui/badge'
import { Alert, AlertDescription, AlertTitle } from '@/components/ui/alert'
import { Skeleton } from '@/components/ui/skeleton'
import { Progress } from '@/components/ui/progress'

// ----- 类型 -----
interface Task {
  id: string
  topic: string
  status: TaskStatus
  mode: string
  preset: string | null
  customStyle: string | null
  customRequirements: string | null
  language: string
  slideCount: number
  audience: string | null
  tone: string | null
  creditsUsed: number
  hasResult: boolean
  errorMessage: string | null
  model: string | null
  durationMs: number | null
  createdAt: string
  startedAt: string | null
  finishedAt: string | null
  progress: number
  progressStage: string | null
}

interface TasksResponse {
  items: Task[]
  total: number
  page: number
  pageSize: number
}

interface DownloadTokenResponse {
  token: string
  expiresAt: string
  downloadUrl: string
}

const PAGE_SIZE = 10

// ----- 任务卡片 -----
interface TaskCardProps {
  task: Task
}

function TaskCard({ task }: TaskCardProps) {
  const meta = statusMeta(task.status)
  const StatusIcon = meta.icon
  const openChat = useAppStore((s) => s.openChat)
  const queryClient = useQueryClient()
  const [downloading, setDownloading] = React.useState(false)
  const [previewOpen, setPreviewOpen] = React.useState(false)
  const [cancelling, setCancelling] = React.useState(false)

  // 是否可预览:已成功且产出文件。预览数据是库里的 deckSpec
  // (GET /api/tasks/[id]/spec);旧任务没有 spec 时弹窗显示"该任务无预览数据"。
  const canPreview = task.status === 'succeeded' && task.hasResult
  // 是否在生成中(pending/generating/finalizing 等)
  const isInProgress = isTaskActive(task.status)

  // 手动取消进行中的任务(退还次数)
  const handleCancel = async () => {
    if (!window.confirm(`确定停止任务「${task.topic.slice(0, 30)}」吗?消耗的次数会退回。`)) return
    setCancelling(true)
    try {
      await apiPost(`/api/tasks/${task.id}/cancel`, {})
      toast.success('任务已停止,次数已退回')
      queryClient.invalidateQueries({ queryKey: ['tasks'] })
    } catch (e) {
      toast.error((e as Error).message || '取消失败')
    } finally {
      setCancelling(false)
    }
  }

  // 副标题(预览用)
  const subtitleParts = [
    task.preset && PRESET_LABELS[task.preset] ? PRESET_LABELS[task.preset] : null,
    task.audience,
    task.tone,
    LANGUAGE_LABELS[task.language] || task.language,
  ].filter(Boolean)
  const previewSubtitle = subtitleParts.join(' | ') || 'Generated by ChatPPT'
  void previewSubtitle // 备用:详情弹窗标题副文案

  const handleDownload = async () => {
    setDownloading(true)
    try {
      const res = await apiPost<DownloadTokenResponse>(
        `/api/tasks/${task.id}/create-download-token`,
        {},
      )
      const a = document.createElement('a')
      a.href = res.downloadUrl
      a.download = `${task.topic.slice(0, 40) || 'chatppt'}.pptx`
      a.style.display = 'none'
      document.body.appendChild(a)
      a.click()
      document.body.removeChild(a)
      toast.success('开始下载,请稍候')
    } catch (e) {
      const err = e as Error
      toast.error(err.message || '下载失败,请稍后重试')
    } finally {
      setDownloading(false)
    }
  }

  return (
    <>
      <Card>
        <CardContent className="p-4 sm:p-5">
          {/* 头部:状态 + 时间 */}
          <div className="mb-3 flex items-start justify-between gap-3">
            <div className="min-w-0 flex-1">
              <h3 className="line-clamp-2 text-base font-semibold leading-snug">
                {task.topic}
              </h3>
              <div className="mt-1.5 flex flex-wrap items-center gap-x-3 gap-y-1 text-xs text-muted-foreground">
                <span className="flex items-center gap-1">
                  <Clock className="size-3" />
                  {formatDate(task.createdAt, 'MM-dd HH:mm')}
                </span>
                <span className="text-muted-foreground/60">·</span>
                <span>{formatRelative(task.createdAt)}</span>
                {task.durationMs != null && (
                  <>
                    <span className="text-muted-foreground/60">·</span>
                    <span>耗时 {formatDuration(task.durationMs)}</span>
                  </>
                )}
              </div>
            </div>
            <Badge
              className={cn(
                'shrink-0 gap-1 [&>svg]:size-3',
                meta.className,
                task.status === 'processing' && '[&>svg]:animate-spin',
              )}
            >
              <StatusIcon className="size-3" />
              {meta.label}
            </Badge>
          </div>

          {/* 元信息 */}
          <div className="mb-3 flex flex-wrap items-center gap-2 text-xs">
            {task.preset && (
              <Badge variant="outline" className="gap-1">
                <Tag className="size-3" />
                {PRESET_LABELS[task.preset] || task.preset}
              </Badge>
            )}
            {task.customStyle && (
              <Badge variant="outline" className="gap-1" title={task.customStyle}>
                <Sparkles className="size-3" />
                自定义风格
              </Badge>
            )}
            <Badge variant="outline" className="gap-1">
              <Languages className="size-3" />
              {LANGUAGE_LABELS[task.language] || task.language}
            </Badge>
            <Badge variant="outline" className="gap-1">
              <Layers className="size-3" />
              {task.slideCount} 张
            </Badge>
            <Badge variant="outline">消耗 {task.creditsUsed} 次</Badge>
            {task.audience && (
              <span className="text-muted-foreground">
                受众:{task.audience}
              </span>
            )}
          </div>

          {/* 失败原因 */}
          {task.errorMessage &&
            (task.status === 'failed' ||
              task.status === 'refunded' ||
              task.status === 'cancelled') && (
            <Alert variant="destructive" className="mb-3 py-3">
              <XCircle className="size-4" />
              <AlertTitle className="text-sm">
                {task.status === 'refunded'
                  ? '已退款'
                  : task.status === 'cancelled'
                    ? '已取消'
                    : '生成失败'}
              </AlertTitle>
              <AlertDescription className="break-all text-xs">
                {task.errorMessage}
              </AlertDescription>
            </Alert>
          )}

          {/* 处理中提示 */}
          {task.status === 'processing' && (
            <Alert className="mb-3 border-amber-500/40 bg-amber-500/10 py-3 text-amber-700 dark:text-amber-400">
              <Loader2 className="size-4 animate-spin" />
              <AlertDescription className="text-xs">
                AI 正在生成中,请耐心等待,页面将自动刷新…
              </AlertDescription>
            </Alert>
          )}

          {/* 进度条 */}
          {isInProgress && (
            <div className="mb-3 space-y-1">
              <div className="flex items-center justify-between text-xs">
                <span className="text-muted-foreground">
                  {task.progressStage || meta.label}
                </span>
                <span className="tabular-nums text-muted-foreground">
                  {task.progress}%
                </span>
              </div>
              <Progress value={task.progress} className="h-1.5" />
            </div>
          )}

          {/* 操作区 */}
          <div className="flex flex-wrap items-center justify-end gap-2 pt-1">
            {isInProgress && (
              <Button
                size="sm"
                variant="outline"
                onClick={handleCancel}
                disabled={cancelling}
                className="gap-1.5 text-destructive hover:bg-destructive/10 hover:text-destructive"
              >
                {cancelling ? (
                  <Loader2 className="size-4 animate-spin" />
                ) : (
                  <Square className="size-3.5" />
                )}
                停止
              </Button>
            )}
            {true && (
              <Button
                size="sm"
                variant="outline"
                onClick={() => openChat(task.id)}
                className="gap-1.5"
              >
                <MessageCircleQuestion className="size-4" />
                查看对话
              </Button>
            )}
            {canPreview && (
              <Button
                size="sm"
                variant="outline"
                onClick={() => setPreviewOpen(true)}
                className="gap-1.5"
              >
                <Eye className="size-4" />
                在线预览
              </Button>
            )}
            {task.status === 'succeeded' && task.hasResult && (
              <Button
                size="sm"
                onClick={handleDownload}
                disabled={downloading}
                className="gap-1.5"
              >
                {downloading ? (
                  <Loader2 className="size-4 animate-spin" />
                ) : (
                  <Download className="size-4" />
                )}
                下载 PPT
              </Button>
            )}
          </div>
        </CardContent>
      </Card>

      {/* 在线预览弹窗(原生 Deck Spec 纸卡,按引擎最终几何渲染) */}
      <NativeDeckPreviewDialog
        open={previewOpen}
        onOpenChange={setPreviewOpen}
        topic={task.topic}
        taskId={task.id}
        downloadFilename={`${task.topic.slice(0, 40) || 'chatppt'}.pptx`}
      />
    </>
  )
}

// ----- 任务列表骨架 -----
function TasksSkeleton() {
  return (
    <div className="space-y-3">
      {Array.from({ length: 3 }).map((_, i) => (
        <Card key={i}>
          <CardContent className="space-y-3 p-4 sm:p-5">
            <Skeleton className="h-5 w-3/4" />
            <Skeleton className="h-3 w-1/2" />
            <Skeleton className="h-7 w-full" />
          </CardContent>
        </Card>
      ))}
    </div>
  )
}

// ----- 主组件 -----
export default function HistoryView() {
  const setView = useAppStore((s) => s.setView)
  const [page, setPage] = React.useState(1)

  const query = useQuery<TasksResponse, Error>({
    queryKey: ['tasks', page],
    queryFn: () =>
      apiGet<TasksResponse>(
        `/api/tasks?page=${page}&pageSize=${PAGE_SIZE}`,
      ),
    refetchInterval: (q) => {
      // 有进行中任务时每 3 秒刷新
      const data = q.state.data
      if (data?.items?.some((t) => isTaskActive(t.status))) {
        return 3000
      }
      return false
    },
    placeholderData: (prev) => prev, // 翻页时保留旧数据避免闪烁
  })

  const tasks = query.data?.items || []
  const total = query.data?.total || 0

  // 加载失败时不算空态,避免错误态被空态吞掉
  const isEmpty = !query.isLoading && !query.isError && tasks.length === 0

  return (
    <motion.div
      initial={{ opacity: 0, y: 8 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.18 }}
      className="mx-auto w-full max-w-5xl px-4 py-6 sm:px-6 sm:py-8"
    >
      {/* 头部 */}
      <div className="mb-6 flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
        <div>
          <div className="mb-1 flex items-center gap-2">
            <div className="flex size-8 items-center justify-center rounded-md bg-primary/10 text-primary">
              <HistoryIcon className="size-5" />
            </div>
            <h1 className="text-xl font-semibold tracking-tight sm:text-2xl">
              生成历史
            </h1>
          </div>
          <p className="text-sm text-muted-foreground">
            查看你的生成任务状态,完成后可在线预览或下载 PPT 文件
          </p>
        </div>
        <Button
          onClick={() => setView('generate')}
          className="w-full sm:w-auto"
          size="lg"
        >
          <Plus className="size-4" />
          立即生成
        </Button>
      </div>

      {/* 内容 */}
      {query.isLoading ? (
        <TasksSkeleton />
      ) : isEmpty ? (
        <Card>
          <CardContent className="flex flex-col items-center justify-center gap-3 px-6 py-16 text-center">
            <div className="flex size-14 items-center justify-center rounded-full bg-muted text-muted-foreground">
              <FileText className="size-7" />
            </div>
            <CardTitle className="text-lg">暂无生成记录</CardTitle>
            <CardDescription className="max-w-sm">
              输入主题、选择风格,让 AI 帮你快速生成 PPT 演示文稿
            </CardDescription>
            <Button
              className="mt-2 w-full sm:w-auto"
              size="lg"
              onClick={() => setView('generate')}
            >
              <Plus className="size-4" />
              立即生成
            </Button>
          </CardContent>
        </Card>
      ) : query.isError ? (
        <Alert variant="destructive">
          <XCircle className="size-4" />
          <AlertTitle>加载失败</AlertTitle>
          <AlertDescription className="flex flex-col items-start gap-3">
            <span>{query.error?.message || '请稍后重试'}</span>
            <Button variant="outline" size="sm" onClick={() => query.refetch()}>
              加载失败,点击重试
            </Button>
          </AlertDescription>
        </Alert>
      ) : (
        <>
          <div className="space-y-3">
            {tasks.map((task) => (
              <TaskCard key={task.id} task={task} />
            ))}
          </div>

          {/* 分页 */}
          <div className="mt-6">
            <PaginationFooter
              page={page}
              pageSize={PAGE_SIZE}
              total={total}
              onPageChange={setPage}
            />
          </div>
        </>
      )}
    </motion.div>
  )
}
