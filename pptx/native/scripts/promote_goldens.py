#!/usr/bin/env python3
"""Promote reviewed render PNGs into the golden baseline directories.

Baselines must come from the *same* renderer that CI uses (Ubuntu LibreOffice +
fonts-noto-cjk), otherwise a locally rendered baseline fails CI on font metrics
alone. So the supported source is the `native-ppt-rendered-demos` artifact:

    # after downloading and unzipping the CI artifact
    python scripts/promote_goldens.py --source path/to/render-check --deck native-components-demo --yes

Each promoted directory gets a MANIFEST.json recording what produced it, so a
later disagreement can be traced to a renderer change instead of being blamed on
the deck.
"""
from __future__ import annotations

import argparse
import datetime
import json
import shutil
import subprocess
import sys
from pathlib import Path

DECKS = [
    "native-demo",
    "native-components-demo",
    "native-design-migration-demo",
    "native-design-parity-demo",
    "native-layouts-demo",
    "native-images-demo",
    "native-stress-deck",
    "pipeline-converted",
    "pipeline-chart",
]


def slide_pngs(folder: Path) -> list[Path]:
    return sorted(path for path in folder.glob("*.png") if path.is_file())


def soffice_version(soffice: str | None) -> str | None:
    if not soffice:
        return None
    try:
        output = subprocess.run([soffice, "--version"], capture_output=True,
                                text=True, timeout=60, check=False).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    return output.strip().splitlines()[0] if output.strip() else None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True,
                        help="directory containing <deck>/*.png renders")
    parser.add_argument("--deck", action="append", default=None,
                        help="deck name to promote (repeatable); default is every deck found")
    parser.add_argument("--golden", type=Path, default=Path("golden"))
    parser.add_argument("--soffice", default=None)
    parser.add_argument("--yes", action="store_true",
                        help="required: confirms the images were reviewed by a human")
    args = parser.parse_args()

    if not args.yes:
        raise SystemExit("Refusing to promote without --yes: baselines are reviewed design contracts.")

    selections = args.deck or [name for name in DECKS if (args.source / name).is_dir()]
    if not selections:
        raise SystemExit(f"No deck folders found under {args.source}")

    promoted = 0
    for deck in selections:
        folder = args.source / deck
        images = slide_pngs(folder)
        if not images:
            print(f"skip {deck}: no PNGs in {folder}")
            continue
        target = args.golden / deck
        target.mkdir(parents=True, exist_ok=True)
        for stale in target.glob("*.png"):
            stale.unlink()
        for image in images:
            shutil.copy2(image, target / image.name)
        manifest = {
            "deck": deck,
            "slides": len(images),
            "images": [image.name for image in images],
            "renderer": "libreoffice",
            "soffice": soffice_version(args.soffice),
            "promoted_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
            "source": str(folder),
            "note": "Generated by the CI renderer (Ubuntu LibreOffice + fonts-noto-cjk). "
                    "Do not regenerate locally: font metrics differ and the comparison will fail.",
        }
        (target / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        print(f"promoted {len(images)} slide(s) into {target}")
        promoted += len(images)

    if not promoted:
        raise SystemExit("Nothing was promoted")
    print("Review `git status` and commit the PNGs with the manifest.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
